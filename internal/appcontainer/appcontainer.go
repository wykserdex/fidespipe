// Package appcontainer запускает внешний код в Windows AppContainer.
//
// Изолятор на Windows устроен не так, как bubblewrap на Linux: там песочница —
// это отдельная программа, которой оборачивают запуск. Здесь изоляция задаётся
// ПРАВАМИ САМОГО ПРОЦЕССА, поэтому обычной обёрткой её не выразить: нужен
// прямой CreateProcessW с атрибутом PROC_THREAD_ATTRIBUTE_SECURITY_CAPABILITIES,
// а os/exec этого не умеет. Отсюда и форма пакета — он создаёт контейнеризованный
// процесс напрямую, а вызывающая сторона запускает его через скрытую подкоманду
// wedra (см. internal/cli/sandbox_exec.go).
//
// Модель безопасности AppContainer: у процесса в контейнере нет ни одной записи
// доступа, кроме явно выданных. Ничего не «монтируется только на чтение», как в
// bwrap: путь либо доступен, либо нет. Это плотнее, а не слабее, но требует
// перечислить всё, что нужно выдать, — в том числе каталог интерпретатора.
//
// Профиль контейнера — на плагин, а не на запуск (решение владельца от
// 2026-10-18): иначе ACL каталога плагина пришлось бы переписывать на каждом
// прогоне и оставлять висящие ACE со ссылкой на удалённый SID. Цена решения —
// одна постоянная запись в DACL каталога плагина; она описана в SECURITY.md.
package appcontainer

import (
	"errors"
	"strings"
)

// ErrUnsupported — на этой платформе AppContainer недоступен.
var ErrUnsupported = errors.New("AppContainer доступен только на Windows")

// ErrHostRefused — хост не смог создать контейнер: политика, отсутствие
// компонентов, запрет на изменение DACL. Отличается от ErrUnsupported: платформа
// подходит, конкретный хост не дал.
var ErrHostRefused = errors.New("хост не разрешил AppContainer")

// Readable — путь, контейнеру нужен только на чтение и исполнение: каталог
// плагина, каталог интерпретатора, сторонние библиотеки.
//
// Каталог плагина попадает сюда же и поэтому остаётся ДОСТУПНЫМ ТОЛЬКО ДЛЯ
// ЧТЕНИЯ: права на запись не выдаются никогда.
type Readable []string

// Plan — что и с какими правами запускать.
type Plan struct {
	// Name — устойчивое имя профиля контейнера. Обычно выводится из id
	// плагина, и переживает перезапуск WEDRA.
	Name string

	// Argv — команда плагина. Argv[0] обязан быть НАСТОЯЩИМ интерпретатором,
	// а не шимбом менеджера пакетов: шимб перенаправляет запуск в соседний
	// каталог, куда у контейнера нет доступа, и ребёнок падает с кодом 5.
	Argv []string

	// Read — пути, выдаваемые контейнеру на чтение и исполнение.
	Read Readable

	// Scratch — приватный записываемый каталог этого запуска.
	Scratch string

	// WorkDir — рабочий каталог ребёнка. Должен лежать внутри Scratch или
	// Read, иначе контейнер не сможет в него войти.
	WorkDir string

	// Env — блок окружения в виде KEY=VALUE.
	Env []string

	// AllowNetwork — разрешить контейнеру выход в сеть.
	//
	// На Windows это capability internetClient (S-1-15-3-1): без неё у
	// контейнера нет сети вообще, и это не «фильтр», а запрет на уровне
	// сетевого стека. Capability выдаётся ПРОЦЕССУ, а не профилю, поэтому
	// один и тот же профиль обслуживает и плагины с сетью, и без неё.
	//
	// Право выдаётся целиком, без разбора по хостам: точечный фильтр не
	// реализован ни на одной платформе (см. internal/plugin/sandbox.go), и
	// обещать плагину «api.telegram.org, и только» было бы враньём.
	AllowNetwork bool
}

// Result — чем закончился контейнеризованный процесс.
type Result struct {
	ExitCode int
}

// ProfileName — устойчивое имя профиля контейнера для плагина.
//
// Имя не должно содержать символов, которые запрещены в имени профиля
// AppContainer, и не должно зависеть от пути на диске: профиль переживает
// переустановку плагина на другое место. Из id плагина берутся только буквы,
// цифры, точка и дефис, остальное отбрасывается.
func ProfileName(pluginID string) string {
	var b strings.Builder
	b.WriteString("wedra.")
	for _, r := range pluginID {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
		case r == '.' || r == '-' || r == '_':
			b.WriteRune(r)
		default:
			b.WriteRune('_')
		}
	}
	// Ядро Windows ограничивает длину имени профиля; запас оставлен на
	// возможный суффикс при коллизии.
	name := b.String()
	const maxProfile = 64
	if len(name) > maxProfile {
		name = name[:maxProfile]
	}
	return name
}

// Validate — проверки, которые не зависят от платформы. Вызывается перед
// созданием процесса, чтобы не оставлять после себя профиль и ACL.
//
// Fail-closed: пустой Argv или пустое имя профила — отказ, а не «запустим как
// получится».
func (p Plan) Validate() error {
	if len(p.Argv) == 0 {
		return errors.New("пустая команда")
	}
	if p.Name == "" {
		return errors.New("пустое имя профиля контейнера")
	}
	if p.Scratch == "" {
		return errors.New("не задан scratch")
	}
	return nil
}
