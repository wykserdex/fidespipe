package plugin

// Подготовка изолятора к запуску плагина.
//
// Вынесена отдельно от самого запуска не для красоты: на Windows подготовка —
// это выдача прав контейнеру на каталог интерпретатора, и выдача эта дорога.
// Windows пересчитывает наследование по всему дереву каталога, а под
// каталогом интерпретатора Python лежит 2,6 ГБ в site-packages: измерено
// 16-18 секунд на выдачу и столько же на повторную.
//
// Повторная выдача стоит столько же — Windows пересчитывает наследование
// заново, даже если ничего не изменилось, — поэтому grant идемпотентен по
// состоянию DCL: если запись для SID контейнера уже есть, выдача не делается
// (см. internal/appcontainer). Итог: 16 секунд платит один раз на плагин.
//
// Платить это на первом прогоне нельзя: человек ждёт запуска плагина, а не
// установки. Поэтому подготовка делается при УСТАНОВКЕ плагина, где её
// терпимо ждать, и на прогоне остаётся проверка DCL — миллисекунды.

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/wykserdex/wedra/internal/pipeline"
)

// PrepareSandbox — готовит изолятор для плагина, установленного в каталог dir.
//
// На Linux делать нечего: bubblewrap собирает песочницу на каждый запуск сам,
// и подготовки не требуется. На Windows — выдача прав контейнеру.
//
// Ошибка here означает, что плагин в песочнице не запустится, но установку
// плагина она НЕ отменяет: плагин может быть доверенным, и решение о
// доверии принимает не установщик.
func PrepareSandbox(dir string) error {
	if dir == "" {
		return nil
	}
	raw, err := os.ReadFile(filepath.Join(dir, "plugin.yaml"))
	if err != nil {
		return fmt.Errorf("не читается plugin.yaml: %w", err)
	}
	var m pipeline.Manifest
	if err := pipeline.DecodeManifest(raw, &m); err != nil {
		return fmt.Errorf("некорректный манифест: %w", err)
	}
	m.Dir = dir
	return prepareSandbox(&m)
}
