/* Исходник фикстуры plugins/community/lief/fixtures/sample.dll.
 *
 * Фикстура — настоящий PE-файл: обёртка проверяется на реальном доноре, а не
 * на подделке. Исходник лежит рядом с бинарником намеренно, чтобы файл можно
 * было пересобрать и сверить, а не принимать на веру:
 *
 *   x86_64-w64-mingw32-gcc -shared -O1 -Wl,--no-insert-timestamp \
 *       -Wl,--image-base,0x180000000 \
 *       -o fixtures/sample.dll fixtures/sample.c
 *
 * Оба флага нужны для повторяемости, и каждый — по своей причине:
 *   - --no-insert-timestamp: без него линкер пишет в COFF-заголовок время
 *     сборки, и два прогона подряд дают разные байты;
 *   - --image-base,0x180000000: у линкера для -shared включён auto image base,
 *     то есть база выбирается СЛУЧАЙНО при каждой линковке (проверено: три
 *     сборки подряд дали 0x371150000, 0x2743d0000 и 0x2485c0000). А LIEF
 *     отдаёт наружу imagebase и entrypoint, поэтому незакреплённая база
 *     означала бы, что ожидаемые значения в plugin.test.yaml зависят от того,
 *     когда файл собрали.
 *
 * Байт-в-байт идентичной пересборки линкер всё равно не даёт: расходятся
 * метка времени в таблице экспорта и контрольная сумма PE (вместе два байта,
 * проверено сравнением двух сборок). На разобранные значения это не влияет —
 * ровно это и утверждают тесты, сверяя вывод донора с зафиксированным файлом.
 *
 * Зачем именно эти импорты. LIEF умеет один и тот же файл показывать как PE,
 * и проверка должна видеть обе стороны:
 *   - .text с флагом SHF/MEM_EXECUTE и .rdata только на чтение — типичная пара;
 *   - .bss, которого в файле нет (SizeOfRawData = 0 при VirtualSize > 0), —
 *     случай, где «размер в файле» и «размер в памяти» не совпадают;
 *   - импорты из KERNEL32.dll и из пары api-ms-win-crt-*: у одного DLL много
 *     символов, у другого мало.
 * Плюс экспорт с именем: у PE есть таблица экспортов, и она видна как секция.
 */
#include <string.h>
#include <stdio.h>
#include <windows.h>

__declspec(dllexport) int fidespipe_fixture_answer(void)
{
    static int counter;            /* уходит в .bss */
    char buf[32];

    memset(buf, 0, sizeof(buf));
    strcpy(buf, "fixture");
    counter++;
    printf("%s %d %lu\n", buf, counter, (unsigned long)GetTickCount());
    return (int)strlen(buf) + counter;
}